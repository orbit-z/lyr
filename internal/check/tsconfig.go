package check

import (
	"encoding/json"
	"errors"
	"io/fs"
	"os"
	"path"
	"path/filepath"
	"strings"
)

// UserTsconfig is what the generated tsconfig needs from the user's root
// tsconfig.json.
type UserTsconfig struct {
	// Include and Exclude are the user's globs, relative to the project
	// root; nil when the file doesn't set them.
	Include, Exclude []string
	// CompilerOptions holds the options orbit doctor looks at.
	CompilerOptions struct {
		// RootDirs is the user's rootDirs (orbit_gen/types belongs there,
		// PLAN.md §5c).
		RootDirs []string
	}
}

// ReadUserTsconfig reads root/tsconfig.json (JSON with comments and
// trailing commas, as tsc accepts). It returns nil when there is none. A
// file that doesn't parse is still extended, with the default include:
// bun check reports its errors.
func ReadUserTsconfig(root string) (*UserTsconfig, error) {
	data, err := os.ReadFile(filepath.Join(root, "tsconfig.json"))
	if errors.Is(err, fs.ErrNotExist) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	u := &UserTsconfig{}
	_ = json.Unmarshal(stripJSONC(data), u)
	return u, nil
}

// stripJSONC removes // and /* */ comments and trailing commas outside
// strings.
func stripJSONC(data []byte) []byte {
	out := make([]byte, 0, len(data))
	for i := 0; i < len(data); i++ {
		c := data[i]
		switch {
		case c == '"':
			j := i + 1
			for j < len(data) && data[j] != '"' {
				if data[j] == '\\' {
					j++
				}
				j++
			}
			j = min(j, len(data)-1)
			out = append(out, data[i:j+1]...)
			i = j
		case c == '/' && i+1 < len(data) && data[i+1] == '/':
			for i < len(data) && data[i] != '\n' {
				i++
			}
			if i < len(data) {
				out = append(out, '\n')
			}
		case c == '/' && i+1 < len(data) && data[i+1] == '*':
			end := strings.Index(string(data[i+2:]), "*/")
			if end < 0 {
				return out
			}
			i += end + 3
		case c == ']' || c == '}':
			// Drop a trailing comma before the closer.
			k := len(out) - 1
			for k >= 0 && (out[k] == ' ' || out[k] == '\t' || out[k] == '\n' || out[k] == '\r') {
				k--
			}
			if k >= 0 && out[k] == ',' {
				out = append(out[:k], out[k+1:]...)
			}
			out = append(out, c)
		default:
			out = append(out, c)
		}
	}
	return out
}

// fromCheckDir rewrites a root-relative tsconfig glob to be relative to
// Dir (two levels down). Absolute globs are kept.
func fromCheckDir(glob string) string {
	if path.IsAbs(glob) || filepath.IsAbs(glob) {
		return glob
	}
	return path.Join("../..", filepath.ToSlash(glob))
}

// typesDir holds the generated .d.ts files (PLAN.md §5c).
const typesDir = "orbit_gen/types"

// defaultOptions are the compilerOptions orbit new scaffolds, plus
// allowImportingTsExtensions (as in Astro's base tsconfig), used when the
// project has no tsconfig.json.
const defaultOptions = `    "target": "ESNext",
    "module": "ESNext",
    "moduleResolution": "Bundler",
    "lib": ["ESNext", "DOM", "DOM.Iterable"],
    "strict": true,
    "noEmit": true,
    "isolatedModules": true,
    "resolveJsonModule": true,
    "allowJs": true,
    "allowImportingTsExtensions": true,
    "skipLibCheck": true,
`

// Tsconfig returns the generated .orbit/check/tsconfig.json. With a user
// tsconfig (u != nil) it extends it, and include is the user's include
// (src/**/*.ts by default) rewritten relative to Dir, plus the extracted
// tree; the user's exclude, if any, is rewritten the same way. Without one
// it uses defaultOptions. rootDirs merges the project root and its mirror
// under Dir, so relative imports in extracted scripts resolve.
func Tsconfig(u *UserTsconfig) string {
	var b strings.Builder
	b.WriteString("// Code generated by orbit check. DO NOT EDIT.\n{\n")
	include := []string{"src/**/*.ts"}
	var exclude []string
	if u != nil {
		b.WriteString("  \"extends\": \"../../tsconfig.json\",\n  \"compilerOptions\": {\n    \"noEmit\": true,\n")
		if u.Include != nil {
			include = u.Include
		}
		exclude = u.Exclude
	} else {
		b.WriteString("  \"compilerOptions\": {\n" + defaultOptions)
	}
	// orbit_gen/types overlays the components' client modules
	// (X.orbit.d.ts) onto src/, and declares orbit:types and orbit:client
	// (PLAN.md §5c), whether or not the user's tsconfig.json says so.
	b.WriteString("    \"rootDirs\": [\"../..\", \".\", \"../../" + typesDir + "\"]\n  },\n")
	globs := make([]string, 0, len(include)+1)
	for _, g := range include {
		globs = append(globs, fromCheckDir(g))
	}
	globs = append(globs, "src/**/*.ts", "../../"+typesDir+"/*.d.ts")
	b.WriteString("  \"include\": " + jsonList(globs))
	if exclude != nil {
		globs = make([]string, 0, len(exclude))
		for _, g := range exclude {
			globs = append(globs, fromCheckDir(g))
		}
		b.WriteString(",\n  \"exclude\": " + jsonList(globs))
	}
	b.WriteString("\n}\n")
	return b.String()
}

func jsonList(s []string) string {
	b, _ := json.Marshal(s)
	return strings.ReplaceAll(string(b), `","`, `", "`)
}
