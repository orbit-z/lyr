// IsReservedIdent reports whether name has a prefix reserved for generated
// code (lyr__ or Lyr__). Such user identifiers are rejected.
func IsReservedIdent(name string) bool {
	return strings.HasPrefix(name, "lyr__") || strings.HasPrefix(name, "Lyr__")
}

// GenPackage locates the two generated packages of one .lyr file
// (PLAN.md §3.1). Rel is the same in both trees.
type GenPackage struct {
	// Rel is the sanitized directory under lyr_gen/decl and lyr_gen/impl,
	// "/"-separated, e.g. "components/card" or "pages/blog/slug_param".
	Rel string
	// Name is the declaration package's name, the last segment of Rel.
	Name string
}

// ImplName is the implementation package's name, Name + "_impl".
func (p GenPackage) ImplName() string { return p.Name + "_impl" }

// DeclDir is the declaration package's directory relative to the module
// root, e.g. "lyr_gen/decl/components/card".
func (p GenPackage) DeclDir() string { return GenDir + "/decl/" + p.Rel }

// ImplDir is the implementation package's directory relative to the module
// root, e.g. "lyr_gen/impl/components/card".
func (p GenPackage) ImplDir() string { return GenDir + "/impl/" + p.Rel }

// DeclFile and ImplFile are the generated files, relative to the module root.
func (p GenPackage) DeclFile() string { return p.DeclDir() + "/" + DeclFileName }
func (p GenPackage) ImplFile() string { return p.ImplDir() + "/" + ImplFileName }

// DeclImportPath and ImplImportPath are the packages' import paths in module.
func (p GenPackage) DeclImportPath(module string) string { return module + "/" + p.DeclDir() }
func (p GenPackage) ImplImportPath(module string) string { return module + "/" + p.ImplDir() }

// PackageFor returns the generated packages of the .lyr file at lyrPath,
// a project-relative "/"-separated path under src/ such as
// "src/components/Card.lyr". The src/ prefix and the .lyr extension are
// dropped and each remaining segment is sanitized (SanitizeSegment); a route
// segment [name] becomes name_param and [...name] becomes name_rest:
//
//	src/components/Card.lyr     → components/card (package card)
//	src/pages/blog/[slug].lyr   → pages/blog/slug_param
//	src/pages/docs/[...rest].lyr → pages/docs/rest_rest
//	src/pages/404.lyr           → pages/p_404
//
// A Markdown file (IsMarkdown) gets an _md suffix on its last segment, so
// it never collides with a sibling .lyr file: src/pages/blog/hello.md →
// pages/blog/hello_md, src/pages/404.md → pages/p_404_md (PLAN.md §2.4).
//
// Collisions between files (my-card.lyr and my_card.lyr) are the
// caller's to report (milestone 5).
func PackageFor(lyrPath string) (GenPackage, error) {
	rest, ok := strings.CutPrefix(lyrPath, "src/")
	md := IsMarkdown(rest)
	if !ok || !strings.HasSuffix(rest, ".lyr") && !md || path.Clean(lyrPath) != lyrPath {
		return GenPackage{}, fmt.Errorf("%s: not a clean .lyr path under src/", lyrPath)
	}
	if md {
		rest = strings.TrimSuffix(rest, path.Ext(rest))
	} else {
		rest = strings.TrimSuffix(rest, ".lyr")
	}
	segs := strings.Split(rest, "/")
	for i, s := range segs {
		if s == "" {
			return GenPackage{}, fmt.Errorf("%s: empty path segment", lyrPath)
		}
		segs[i] = sanitizeRouteSegment(s)
	}
	if md {
		segs[len(segs)-1] += "_md"
	}
	return GenPackage{Rel: strings.Join(segs, "/"), Name: segs[len(segs)-1]}, nil
}

func sanitizeRouteSegment(s string) string {
	if strings.HasPrefix(s, "[...") && strings.HasSuffix(s, "]") && len(s) > 5 {
		return sanitizeBase(s[4:len(s)-1]) + "_rest"
	}
	if strings.HasPrefix(s, "[") && strings.HasSuffix(s, "]") && len(s) > 2 && !strings.ContainsAny(s[1:len(s)-1], "[]") {
		return sanitizeBase(s[1:len(s)-1]) + "_param"
	}
	return SanitizeSegment(s)
}

// SanitizeSegment turns one path segment into a Go package name: it is
// lowercased, and every byte other than a-z, 0-9 and _ becomes _. The result
// gets a p_ prefix when it is a Go keyword, main or init, starts with a digit
// or _, or is testdata, vendor or internal (names the go command treats
// specially in directories).
func SanitizeSegment(s string) string {
	b := sanitizeBase(s)
	if b == "" || gotoken.IsKeyword(b) || b[0] == '_' || b[0] >= '0' && b[0] <= '9' {
		return "p_" + b
	}
	switch b {
	case "main", "init", "testdata", "vendor", "internal":
		return "p_" + b
	}
	return b
}

func sanitizeBase(s string) string {
	s = strings.ToLower(s)
	var b strings.Builder
	for i := 0; i < len(s); {
		r, size := utf8.DecodeRuneInString(s[i:])
		if r < utf8.RuneSelf && (r >= 'a' && r <= 'z' || r >= '0' && r <= '9' || r == '_') {
			b.WriteRune(r)
		} else {
			b.WriteByte('_')
		}
		i += size
	}
	return b.String()
}

// DirectiveFile returns the file name a line directive in genFile uses for
// lyrPath: the path of lyrPath relative to genFile's directory, with "/"
// separators (PLAN.md §3.3). Both paths are module-relative, e.g.
// DirectiveFile("lyr_gen/impl/components/card/render.go",
// "src/components/Card.lyr") = "../../../../src/components/Card.lyr".
func DirectiveFile(genFile, lyrPath string) string {
	depth := strings.Count(path.Dir(genFile), "/") + 1
	return strings.Repeat("../", depth) + lyrPath
}

// ScopeHash returns the 8 hex characters of the sha256 of a project-relative,
// "/"-separated .lyr path (PLAN.md §5). Scope IDs are "o-" + ScopeHash.
func ScopeHash(lyrPath string) string {
	sum := sha256.Sum256([]byte(lyrPath))
	return hex.EncodeToString(sum[:4])
}

// ComponentID returns the component ID of the .lyr file at lyrPath: its
// base name without .lyr, "-", and its ScopeHash (PLAN.md §3.4), e.g.
// "src/components/Comments.lyr" → "Comments-<hash8>".
//
// A Markdown file's extension is dropped the same way
// ("src/content/intro.md" → "intro-<hash8>").
func ComponentID(lyrPath string) string {
	return TrimSourceExt(lyrPath) + "-" + ScopeHash(lyrPath)
}

// initialisms is golint's common-initialisms table, as listed in
// docs/reference/template-syntax.md.
var initialisms = map[string]bool{
	"ACL": true, "API": true, "ASCII": true, "CPU": true, "CSS": true, "DNS": true, "EOF": true,
	"GUID": true, "HTML": true, "HTTP": true, "HTTPS": true, "ID": true, "IP": true, "JSON": true,
	"LHS": true, "QPS": true, "RAM": true, "RHS": true, "RPC": true, "SLA": true, "SMTP": true,
	"SQL": true, "SSH": true, "TCP": true, "TLS": true, "TTL": true, "UDP": true, "UI": true,
	"UID": true, "UUID": true, "URI": true, "URL": true, "UTF8": true, "VM": true, "XML": true,
	"XMPP": true, "XSRF": true, "XSS": true,
}

// FieldName converts an attribute or route param name to a Go field name
// (PLAN.md §2.2, §2.3): the name is split into words at '-', '_' and
// lower-to-upper case changes; a word whose upper case is in golint's
// initialism table is written in capitals, any other word gets its first
// letter capitalized and keeps the rest as written:
//
//	slug → Slug, post-id → PostID, postId → PostID, id → ID, api-url → APIURL,
//	is_open → IsOpen, HTTPServer → HTTPServer
//
// It doesn't validate the result; callers check it is an exported identifier.
func FieldName(name string) string {
	var b strings.Builder
	for _, w := range splitWords(name) {
		if up := strings.ToUpper(w); initialisms[up] {
			b.WriteString(up)
			continue
		}
		r, size := utf8.DecodeRuneInString(w)
		b.WriteRune(unicode.ToUpper(r))
		b.WriteString(w[size:])
	}
	return b.String()
}

func splitWords(s string) []string {
	var words []string
	start := 0
	prevLower := false
	for i, r := range s {
		switch {
		case r == '-' || r == '_':
			if i > start {
				words = append(words, s[start:i])
			}
			start = i + 1
			prevLower = false
			continue
		case prevLower && unicode.IsUpper(r):
			words = append(words, s[start:i])
			start = i
		}
		prevLower = unicode.IsLower(r)
	}
	if start < len(s) {
		words = append(words, s[start:])
	}
	return words
}

// LowerCamel returns the attribute spelling of a Props field, used to list
// the valid props in the unknown-prop error (PLAN.md §2.3): the leading run
// of capitals is lowercased, except its last capital when a lowercase letter
// follows it, as Go names unexported identifiers:
//
//	Title → title, IsOpen → isOpen, ID → id, UserID → userID, HTTPServer → httpServer
func LowerCamel(field string) string {
	rs := []rune(field)
	n := 0
	for n < len(rs) && unicode.IsUpper(rs[n]) {
		n++
	}
	if n > 1 && n < len(rs) && unicode.IsLower(rs[n]) {
		n--
	}
	for i := 0; i < n; i++ {
		rs[i] = unicode.ToLower(rs[i])
	}
	return string(rs)
}

// NormalizeName returns the key that attribute names and Props field names
// are matched by: lowercased, with '-' and '_' removed (PLAN.md §2.3), so
// is-open, isOpen and IsOpen all match.
func NormalizeName(s string) string {
	for i := 0; i < len(s); i++ {
		if c := s[i]; c == '-' || c == '_' || c >= utf8.RuneSelf || 'A' <= c && c <= 'Z' {
			return strings.ToLower(nameSeparators.Replace(s))
		}
	}
	return s // already a key: the common case of a lowercase attribute name
}

// nameSeparators removes the separators NormalizeName ignores. It's built
// once: a strings.Replacer builds its tables on first use, which costs
// more than the replacement itself.
var nameSeparators = strings.NewReplacer("-", "", "_", "")

// ErrNoField is returned by MatchProp when the attribute matches no field
// of a listable Props.
var ErrNoField = errors.New("no such prop")

// MatchProp returns the Props field that the component attribute attr sets
// (PLAN.md §2.3). A field whose NormalizeName equals attr's wins. If none
// does and props.Listable is false (embedded field or non-struct Props),
// the field is FieldName(attr) and Go checks it; otherwise ErrNoField, and
// the caller reports the unknown prop.
func MatchProp(props *PropsInfo, attr string) (string, error) {
	key := NormalizeName(attr)
	for _, f := range props.Fields {
		if NormalizeName(f.Name) == key {
			return f.Name, nil
		}
	}
	if !props.Listable {
		return FieldName(attr), nil
	}
	return "", ErrNoField
}

// urlAttrs mirrors the runtime's list (writer.go urlAttrs); a test checks the
// two agree through the runtime's behavior.
var urlAttrs = [...]string{
	"action", "background", "cite", "codebase", "data", "formaction",
	"href", "icon", "longdesc", "manifest", "poster", "profile", "src",
	"usemap", "xmlns", "xlink:href",
}

// IsURLAttr reports whether the attribute name (in any case) holds a URL, so
// a typed string value is written with URL (scheme-filtered) rather than String.
func IsURLAttr(name string) bool {
	for _, a := range urlAttrs {
		if strings.EqualFold(a, name) {
			return true
		}
	}
	return false
}

// trueFalseAttrs mirrors the runtime's list (writer.go trueFalseAttrs): the
// HTML attributes whose keywords are "true" and "false" (PLAN.md §2.6
// (Q3)); a test checks the two agree through the runtime's behavior.
var trueFalseAttrs = [...]string{"contenteditable", "draggable", "spellcheck", "writingsuggestions"}

// IsTrueFalseAttr reports whether the attribute name (in any case) takes
// the keywords true and false, every aria-* attribute included: a bool is
// written there as name="true" or name="false", not bare or omitted.
func IsTrueFalseAttr(name string) bool {
	if len(name) > len("aria-") && strings.EqualFold(name[:len("aria-")], "aria-") {
		return true
	}
	for _, a := range trueFalseAttrs {
		if strings.EqualFold(a, name) {
			return true
		}
	}
	return false
}

// isUnsafeURL mirrors the runtime's URL filter (writer.go isUnsafeURL), for
// constants folded at build time: a javascript: or vbscript: scheme,
// ignoring case, leading whitespace and control characters, and tabs and
// newlines anywhere in the scheme.
func isUnsafeURL(u string) bool {
	i := 0
	for i < len(u) && (u[i] <= ' ' || u[i] == 0x7f) {
		i++
	}
	return hasSchemeFold(u[i:], "javascript:") || hasSchemeFold(u[i:], "vbscript:")
}

func hasSchemeFold(u, scheme string) bool {
	j := 0
	for i := 0; i < len(u) && j < len(scheme); i++ {
		c := u[i]
		if c == '\t' || c == '\n' || c == '\r' {
			continue
		}
		if 'A' <= c && c <= 'Z' {
			c += 'a' - 'A'
		}
		if c != scheme[j] {
			return false
		}
		j++
	}
	return j == len(scheme)
}

