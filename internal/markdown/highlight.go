package markdown

import (
	"fmt"
	"slices"
	"strings"
	"sync"

	"github.com/alecthomas/chroma/v2"
	"github.com/alecthomas/chroma/v2/lexers"
	"github.com/alecthomas/chroma/v2/styles"
)

// Code highlighting (PLAN.md §2.4): Orbit's own code-block renderer over
// Chroma, writing Chroma's class names, and the light-dark() stylesheet
// generated from two Chroma styles.

// lexerCache memoizes lexers.Get by language name, misses included: for a
// name Chroma doesn't know (mermaid), Get falls back to matching it
// against every lexer's filename globs, about 1.5 ms a call.
var lexerCache sync.Map // lowercased name → chroma.Lexer (nil for none)

// lexerFor returns the coalescing lexer for a fenced block's language, or
// nil when Chroma doesn't know it. "orbit" is Orbit's own lexer
// (orbitlexer.go).
func lexerFor(lang string) chroma.Lexer {
	key := strings.ToLower(lang)
	if l, ok := lexerCache.Load(key); ok {
		lx, _ := l.(chroma.Lexer)
		return lx
	}
	var lx chroma.Lexer
	if key == "orbit" {
		lx = orbitLexer()
	} else if l := lexers.Get(key); l != nil {
		lx = chroma.Coalesce(l)
	}
	if lx == nil {
		lexerCache.Store(key, nil)
	} else {
		lexerCache.Store(key, lx)
	}
	return lx
}

var codeEscaper = strings.NewReplacer("&", "&amp;", "<", "&lt;", ">", "&gt;")

// highlight writes code as Chroma token spans; ok is false when the
// language is unknown or tokenizing fails (the caller writes it escaped).
func highlight(b *strings.Builder, lang, code string) bool {
	lx := lexerFor(lang)
	if lx == nil {
		return false
	}
	it, err := lx.Tokenise(nil, code)
	if err != nil {
		return false
	}
	var out strings.Builder
	for t := it(); t != chroma.EOF; t = it() {
		cls := tokenClass(t.Type)
		if cls == "" || t.Type == chroma.TextWhitespace {
			codeEscaper.WriteString(&out, t.Value)
			continue
		}
		out.WriteString(`<span class="` + cls + `">`)
		codeEscaper.WriteString(&out, t.Value)
		out.WriteString(`</span>`)
	}
	b.WriteString(out.String())
	return true
}

// Highlight returns code as HTML spans with Chroma's token classes (styled
// by HighlightCSS) for a fenced block's language, "orbit" included; ok is
// false when the language is unknown. Orbit's docs site (docs/site) uses it
// in its own Markdown renderer.
func Highlight(lang, code string) (html string, ok bool) {
	var b strings.Builder
	if !highlight(&b, lang, code) {
		return "", false
	}
	return b.String(), true
}

// tokenClass is Chroma's CSS class for a token type: its own, or its
// nearest ancestor's ("" for plain text), as Chroma's HTML formatter picks
// it.
func tokenClass(t chroma.TokenType) string {
	for t != 0 {
		if cls, ok := chroma.StandardTypes[t]; ok {
			return cls
		}
		t = t.Parent()
	}
	return chroma.StandardTypes[t]
}

// HighlightCSS returns the stylesheet for highlighted code blocks
// (orbit:style/markdown-highlight.css): one rule per Chroma token class,
// each color written as light-dark(<light>, <dark>), and non-color
// properties from the light theme. With SingleTheme, the light theme's
// colors are written as is. "" when highlighting or its CSS is off.
func HighlightCSS(o Options) string {
	if o.NoHighlight || o.NoCSS {
		return ""
	}
	key := o.LightTheme() + "\x00" + o.DarkTheme()
	if css, ok := cssCache.Load(key); ok {
		return css.(string)
	}
	css := themeCSS(styles.Get(o.LightTheme()), darkStyle(o))
	cssCache.Store(key, css)
	return css
}

var cssCache sync.Map

func darkStyle(o Options) *chroma.Style {
	if o.DarkTheme() == "" {
		return nil
	}
	return styles.Get(o.DarkTheme())
}

func themeCSS(light, dark *chroma.Style) string {
	var b strings.Builder
	b.WriteString("/* Code highlighting: Chroma themes " + light.Name)
	if dark != nil {
		b.WriteString(" (light) and " + dark.Name + " (dark)")
	}
	b.WriteString(", generated by Orbit. */\n")
	lbg := light.Get(chroma.Background)
	var dbg chroma.StyleEntry
	if dark != nil {
		dbg = dark.Get(chroma.Background)
	}
	// A theme without a text or background color (github has no text
	// color) falls back to the page's system colors.
	col := func(c chroma.Colour, fallback string) string {
		if c.IsSet() {
			return c.String()
		}
		return fallback
	}
	color := func(l, d chroma.Colour, fallback string) string {
		ls, ds := col(l, fallback), col(d, fallback)
		if dark == nil || ls == ds {
			return ls
		}
		return "light-dark(" + ls + ", " + ds + ")"
	}
	// The block: the themes' text and background colors.
	fmt.Fprintf(&b, ".chroma { color: %s; background-color: %s; }\n",
		color(lbg.Colour, dbg.Colour, "CanvasText"), color(lbg.Background, dbg.Background, "Canvas"))

	types := make([]chroma.TokenType, 0, len(chroma.StandardTypes))
	for t := range chroma.StandardTypes {
		if t >= 0 || t == chroma.Error {
			types = append(types, t)
		}
	}
	slices.Sort(types)
	seen := map[string]bool{}
	for _, t := range types {
		cls := chroma.StandardTypes[t]
		if cls == "" || seen[cls] || t == chroma.TextWhitespace {
			continue
		}
		seen[cls] = true
		l := light.Get(t).Sub(lbg)
		var d chroma.StyleEntry
		if dark != nil {
			d = dark.Get(t).Sub(dbg)
		}
		var props []string
		// A side that doesn't style the token keeps the block's color.
		if l.Colour.IsSet() || d.Colour.IsSet() {
			lc, dc := l.Colour, d.Colour
			if !lc.IsSet() {
				lc = lbg.Colour
			}
			if !dc.IsSet() {
				dc = dbg.Colour
			}
			props = append(props, "color: "+color(lc, dc, "CanvasText"))
		}
		if l.Background.IsSet() || d.Background.IsSet() {
			lc, dc := l.Background, d.Background
			if !lc.IsSet() {
				lc = lbg.Background
			}
			if !dc.IsSet() {
				dc = dbg.Background
			}
			props = append(props, "background-color: "+color(lc, dc, "Canvas"))
		}
		if l.Bold == chroma.Yes {
			props = append(props, "font-weight: bold")
		}
		if l.Italic == chroma.Yes {
			props = append(props, "font-style: italic")
		}
		if l.Underline == chroma.Yes {
			props = append(props, "text-decoration: underline")
		}
		if len(props) == 0 {
			continue
		}
		fmt.Fprintf(&b, ".chroma .%s { %s }\n", cls, strings.Join(props, "; "))
	}
	return b.String()
}
