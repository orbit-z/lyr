// Command gen bundles and minifies the client loader (loader/*.ts) with
// esbuild and writes loader_gen.go at the repository root, holding the two
// scripts as string constants the runtime embeds (PLAN.md §4 "Loader").
//
// It runs through the //go:generate line in loader.go. It's a separate
// main package so that the runtime package stays stdlib-only.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"strconv"
	"strings"

	"github.com/evanw/esbuild/pkg/api"
)

// scripts maps each constant to its entry, relative to the repository root.
var scripts = []struct{ name, entry, doc string }{
	{"loaderIslandsJS", "loader/islands.ts", "fetches every <lyr-island> and swaps in its fragment."},
	{"loaderLazyJS", "loader/lazy.ts", "observes <lyr-lazy> markers and imports their entries."},
}

func main() {
	root := flag.String("root", ".", "repository root")
	flag.Parse()
	src, err := generate(*root)
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(*root, "loader_gen.go"), src, 0o644); err != nil {
		log.Fatal(err)
	}
}

// generate returns the content of loader_gen.go.
func generate(root string) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString(`// Code generated by loader/internal/gen. DO NOT EDIT.

package lyr

// The client loader (PLAN.md §5 "The loader"), built from loader/*.ts.
// Run "go generate" at the repository root after editing loader/.
//
// Injection contract (head injection, only on pages that need it):
//
//	<style>lyr-island,lyr-lazy{display:contents}</style>
//	<script type="application/json" id="lyr-loader">{"dev":false,"lazy":{"Counter-1c2d3e4f":"/_lyr/Counter-HASH.js"}}</script>
//	<script type="module">…loaderIslandsJS…</script>   (when Route.Islands)
//	<script type="module">…loaderLazyJS…</script>      (when the page has lazy assets)
//
// The JSON config comes first; each script reads it on its own, so either
// works without the other. "dev" enables console errors and warnings.
// "lazy" maps component IDs to an entry URL or a list of entry URLs. When
// both scripts are on a page, the islands script hands the nodes it sees
// added (island fragments included) to the lazy script through
// window.lyr__lazy.
`)
	for _, s := range scripts {
		js, err := build(filepath.Join(root, s.entry))
		if err != nil {
			return nil, err
		}
		fmt.Fprintf(&b, "\n// %s %s\nconst %s = %s\n", s.name, s.doc, s.name, strconv.Quote(js))
	}
	return format.Source(b.Bytes())
}

func build(entry string) (string, error) {
	res := api.Build(api.BuildOptions{
		EntryPoints:       []string{entry},
		Bundle:            true,
		Write:             false,
		Format:            api.FormatESModule,
		Target:            api.ES2020,
		Platform:          api.PlatformBrowser,
		MinifySyntax:      true,
		MinifyWhitespace:  true,
		MinifyIdentifiers: true,
		LegalComments:     api.LegalCommentsNone,
		Charset:           api.CharsetUTF8,
		LogLevel:          api.LogLevelSilent,
	})
	if len(res.Errors) > 0 {
		msgs := api.FormatMessages(res.Errors, api.FormatMessagesOptions{Kind: api.ErrorMessage})
		return "", fmt.Errorf("esbuild %s:\n%s", entry, strings.Join(msgs, ""))
	}
	if len(res.OutputFiles) != 1 {
		return "", fmt.Errorf("esbuild %s: %d output files, want 1", entry, len(res.OutputFiles))
	}
	return strings.TrimSpace(string(res.OutputFiles[0].Contents)), nil
}
