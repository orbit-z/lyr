// Command gen bundles and minifies the client loader (loader/loader.ts)
// with esbuild and writes internal/loader/loader_gen.go: the loader files
// lyr build and lyr dev write under /_lyr/loader/, named by a hash of
// their contents, and their URLs, which the runtime injects (PLAN.md §5
// "The loader", §5f).
//
// It runs through the //go:generate line in loader.go. It's a separate
// main package so that the runtime stays stdlib-only.
package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"strconv"
	"strings"

	"github.com/evanw/esbuild/pkg/api"
)

// wrappersCSS makes the loader's wrapper elements boxless, so they don't
// change the layout. It's wrappers-<hash>.css, which page partials link,
// and the first rule of the stylesheet of every page with a server:defer
// or client:* call site.
const wrappersCSS = "lyr-island,lyr-lazy{display:contents}"

// out is the generated file, relative to the repository root.
const out = "internal/loader/loader_gen.go"

func main() {
	root := flag.String("root", ".", "repository root")
	flag.Parse()
	src, err := generate(*root)
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(*root, out), src, 0o644); err != nil {
		log.Fatal(err)
	}
}

// name returns the file name of contents: base-<hash8>.ext, where hash8
// is the first 8 hex digits of its SHA-256.
func name(base, ext, contents string) string {
	sum := sha256.Sum256([]byte(contents))
	return base + "-" + hex.EncodeToString(sum[:4]) + ext
}

// generate returns the content of internal/loader/loader_gen.go.
func generate(root string) ([]byte, error) {
	js, err := build(filepath.Join(root, "loader", "loader.ts"))
	if err != nil {
		return nil, err
	}
	jsName, cssName := name("loader", ".js", js), name("wrappers", ".css", wrappersCSS)
	var b bytes.Buffer
	fmt.Fprintf(&b, `// Code generated by loader/internal/gen. DO NOT EDIT.

// Package loader holds the client loader files (PLAN.md §5 "The loader",
// §5f), built from loader/*.ts. Run "go generate" at the repository root
// after editing loader/.
//
// lyr build and lyr dev write Files into dist/client/_lyr/ (dev: .lyr/dev/_lyr/),
// served as ordinary immutable static files. The runtime injects the URLs.
//
// Injection contract. A page whose static graph has a server:defer or
// client:* call site gets, in its head, before its own tags:
//
//	<script type="application/json" id="lyr-loader">{"dev":false,"lazy":{"Counter-1c2d3e4f":["/_lyr/Counter-HASH.js"]}}</script>
//	<script defer src="%[1]s"></script>
//
// and WrappersCSS first in its stylesheet. A page partial (PLAN.md §4k)
// that needs it ends with:
//
//	<link rel="stylesheet" href="%[2]s">   (when it has call sites)
//	<script src="%[1]s" data-lyr-loader='{"dev":false,"lazy":{…},"ids":{…},"run":[["ID","URL"],…]}'></script>
//
// "dev" enables console errors and warnings. "lazy" maps component IDs to
// an entry URL or a list of entry URLs. "ids" maps a partial's lazy URLs to
// their component IDs, "run" lists the component entries it imports unless
// the document ran them (window.lyr__ran). The script is classic, so it runs
// on every insertion; the islands and lazy loaders install once per
// document (window.lyr__islands, window.lyr__lazy) and later runs merge
// their config into them. Every imported URL must resolve to this origin
// under /_lyr/, and every fetched island src under /_lyr/island/.
//
// Deploy skew: lyr__ran is still a Set of component IDs, lyr__lazy still
// takes (nodes, merge), and lyr__islands.w is true, so a v0.2 partial's
// inline loaders in a newer page install nothing again. A newer partial in
// a v0.2 page runs its components and islands, but the v0.2 lazy loader
// doesn't read the attribute config: its lazy components don't load.
package loader

const (
	// LoaderURL is the loader script.
	LoaderURL = %[1]q
	// WrappersURL is the stylesheet holding WrappersCSS.
	WrappersURL = %[2]q
	// WrappersCSS makes <lyr-island> and <lyr-lazy> boxless.
	WrappersCSS = %[3]q
)

// File is one loader file. Path is relative to /_lyr/ ("loader/loader-1a2b3c4d.js").
type File struct{ Path, Contents string }

// Files are the loader files, for lyr build and lyr dev to write.
var Files = []File{
	{%[4]q, loaderJS},
	{%[5]q, WrappersCSS},
}

// loaderJS is the loader script: a classic script (an IIFE).
const loaderJS = %[6]s
`, "/_lyr/loader/"+jsName, "/_lyr/loader/"+cssName, wrappersCSS,
		"loader/"+jsName, "loader/"+cssName, strconv.Quote(js))
	return format.Source(b.Bytes())
}

// build bundles entry as a minified classic script: an IIFE, so it has no
// top-level import or export and runs on every insertion.
func build(entry string) (string, error) {
	res := api.Build(api.BuildOptions{
		EntryPoints:       []string{entry},
		Bundle:            true,
		Write:             false,
		Format:            api.FormatIIFE,
		Target:            api.ES2020,
		Platform:          api.PlatformBrowser,
		MinifySyntax:      true,
		MinifyWhitespace:  true,
		MinifyIdentifiers: true,
		LegalComments:     api.LegalCommentsNone,
		Charset:           api.CharsetUTF8,
		LogLevel:          api.LogLevelSilent,
	})
	if len(res.Errors) > 0 {
		msgs := api.FormatMessages(res.Errors, api.FormatMessagesOptions{Kind: api.ErrorMessage})
		return "", fmt.Errorf("esbuild %s:\n%s", entry, strings.Join(msgs, ""))
	}
	if len(res.OutputFiles) != 1 {
		return "", fmt.Errorf("esbuild %s: %d output files, want 1", entry, len(res.OutputFiles))
	}
	return strings.TrimSpace(string(res.OutputFiles[0].Contents)), nil
}
