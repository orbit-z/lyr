// Command gensite writes a synthetic Lyr project (pass-1 output: every
// template expression goes through lyr__w.Expr) in the PLAN.md §3.1 layout.
//
//	go run ./cmd/gensite -n 50 -out sites/s50
package main

import (
	"flag"
	"fmt"
	"log"
	"math/rand/v2"
	"os"
	"path/filepath"
	"strings"
)

const mod = "example.com/site"

func main() {
	n := flag.Int("n", 50, "number of components (20% are pages)")
	out := flag.String("out", "sites/s50", "output dir")
	stub := flag.String("stub", "", "absolute path of the lyr stub module (default: ../../lyrstub relative to out)")
	flag.Parse()

	if err := os.RemoveAll(*out); err != nil {
		log.Fatal(err)
	}
	rng := rand.New(rand.NewPCG(42, uint64(*n)))
	stubPath := *stub
	if stubPath == "" {
		stubPath = "../../lyrstub"
	}
	write(*out, "go.mod", fmt.Sprintf("module %s\n\ngo 1.27\n\ntoolchain go1.27.3\n\nrequire github.com/bertrandkhe/lyr v0.0.0\n\nreplace github.com/bertrandkhe/lyr => %s\n", mod, stubPath))
	write(*out, "internal/posts/posts.go", postsSrc)

	nPages := *n / 5
	type comp struct{ name, dir, file string }
	var comps, pages []comp
	for i := 0; i < *n; i++ {
		if i < nPages {
			name := fmt.Sprintf("p%03d", i)
			pages = append(pages, comp{name, "pages/" + name, fmt.Sprintf("src/pages/%s.lyr", name)})
		} else {
			name := fmt.Sprintf("c%03d", i)
			comps = append(comps, comp{name, "components/" + name, fmt.Sprintf("src/components/%s.lyr", name)})
		}
	}
	all := append(append([]comp{}, pages...), comps...)
	for _, c := range all {
		write(*out, "lyr_gen/decl/"+c.dir+"/decl.go", declSrc(c.name, c.file))
		// 3-5 children, always components (never pages), may form cycles.
		k := 3 + rng.IntN(3)
		seen := map[string]bool{c.name: true}
		var kids []string
		for len(kids) < k {
			ch := comps[rng.IntN(len(comps))]
			if !seen[ch.name] {
				seen[ch.name] = true
				kids = append(kids, ch.name)
			}
		}
		write(*out, "lyr_gen/impl/"+c.dir+"/render.go", implSrc(c.name, c.dir, c.file, kids, rng.IntN(4) == 0))
	}

	var app strings.Builder
	app.WriteString("// Code generated by lyr. DO NOT EDIT.\n\npackage app\n\nimport (\n\tlyr \"github.com/bertrandkhe/lyr\"\n")
	for _, p := range pages {
		fmt.Fprintf(&app, "\t%s %q\n", strings.ToUpper(p.name[:1])+p.name[1:], mod+"/lyr_gen/decl/"+p.dir)
	}
	for _, c := range all {
		fmt.Fprintf(&app, "\t_ %q\n", mod+"/lyr_gen/impl/"+c.dir)
	}
	app.WriteString(")\n\ntype Page struct {\n\tName   string\n\tRender func(*lyr.Ctx, *lyr.Writer) error\n}\n\nvar Pages = []Page{\n")
	for _, p := range pages {
		alias := strings.ToUpper(p.name[:1]) + p.name[1:]
		fmt.Fprintf(&app, "\t{%q, func(ctx *lyr.Ctx, w *lyr.Writer) error { return %s.Render(ctx, w, %s.Props{Title: %q}, lyr.Slots{}) }},\n", p.name, alias, alias, p.name)
	}
	app.WriteString("}\n")
	write(*out, "lyr_gen/app/app.go", app.String())
	write(*out, "lyr_gen/cmd/render/main.go", renderMain)
}

func write(root, rel, content string) {
	p := filepath.Join(root, rel)
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
		log.Fatal(err)
	}
}

func declSrc(name, file string) string {
	return fmt.Sprintf(`// Code generated by lyr. DO NOT EDIT.

package %[1]s

import (
	lyr "github.com/bertrandkhe/lyr"
	"example.com/site/internal/posts"
)

type Props struct {
	Title    string
	Post     posts.Post
	Count    int
	Featured bool
	Depth    int
	Author   *posts.Author
}

var Lyr__Render func(*lyr.Ctx, *lyr.Writer, Props, lyr.Slots) error

func Render(ctx *lyr.Ctx, w *lyr.Writer, props Props, slots lyr.Slots) error {
	if Lyr__Render == nil {
		panic("lyr: %[2]s not linked; import example.com/site/lyr_gen/app")
	}
	return Lyr__Render(ctx, w, props, slots)
}
`, name, file)
}

func implSrc(name, dir, file string, kids []string, self bool) string {
	var b strings.Builder
	fmt.Fprintf(&b, `// Code generated by lyr. DO NOT EDIT.

package %s

import (
	lyr "github.com/bertrandkhe/lyr"
	. "example.com/site/lyr_gen/decl/%s"
	"example.com/site/internal/posts"
	"strings"
`, name, dir)
	for _, k := range kids {
		fmt.Fprintf(&b, "\t%s \"example.com/site/lyr_gen/decl/components/%s\"\n", alias(k), k)
	}
	fmt.Fprintf(&b, `)

func heading(p Props) string { return strings.Repeat("#", p.Depth+1) + " " + p.Title }

type badge struct{ Label string }

func (b badge) String() string { return "[" + b.Label + "]" }

func init() { Lyr__Render = lyr__render }

func lyr__render(ctx *lyr.Ctx, lyr__w *lyr.Writer, props Props, slots lyr.Slots) error {
	if lyr__err := lyr__w.Enter(%q); lyr__err != nil {
		return lyr__err
	}
	defer lyr__w.Leave()
	locals := lyr.LocalsOf[lyr.NoLocals](ctx)
	_, _, _, _ = ctx, props, slots, locals
	list := posts.All()
	title := strings.ToUpper(props.Title)
	n := len(list)
	first := list[0]
	b := badge{Label: props.Title}
	var err error
	_, _, _, _, _ = list, title, n, first, b
	lyr__w.Raw("<section class=\"%s\"><h2>")
	lyr__w.Expr(title)
	lyr__w.Raw("</h2>\n<p class=\"meta\">")
	lyr__w.Expr(props.Post.Title)
	lyr__w.Raw(" / ")
	lyr__w.Expr(props.Post.Slug)
	lyr__w.Raw(" / ")
	lyr__w.Expr(props.Count)
	lyr__w.Raw(" / ")
	lyr__w.Expr(n)
	lyr__w.Raw(" / ")
	lyr__w.Expr(props.Featured)
	lyr__w.Raw(" / ")
	lyr__w.Expr(first.Status)
	lyr__w.Raw(" / ")
	lyr__w.Expr(props.Author)
	lyr__w.Raw(" / ")
	lyr__w.Expr(first.Author)
	lyr__w.Raw(" / ")
	lyr__w.Expr(first.Created)
	lyr__w.Raw(" / ")
	lyr__w.Expr(first.Score)
	lyr__w.Raw(" / ")
	lyr__w.Expr(first.Body)
	lyr__w.Raw(" / ")
	lyr__w.Expr(heading(props))
	lyr__w.Raw(" / ")
	lyr__w.Expr(first.URL())
	lyr__w.Raw(" / ")
	lyr__w.Expr(len(first.Tags))
	lyr__w.Raw(" / ")
	lyr__w.Expr(posts.Tag("go"))
	lyr__w.Raw(" / ")
	lyr__w.Expr(lyr.HTML("<b>raw</b>"))
	lyr__w.Raw(" / ")
	lyr__w.Expr("a < b")
	lyr__w.Raw(" / ")
	lyr__w.Expr(props.Depth + 1)
	lyr__w.Raw(" / ")
	lyr__w.Expr(first.Price)
	lyr__w.Raw(" / ")
	lyr__w.Expr(b)
	lyr__w.Raw(" / ")
	lyr__w.Expr(err)
	lyr__w.Raw(" / ")
	lyr__w.Expr(any(props.Count))
	lyr__w.Raw("</p>\n<ul>")
	for _, p := range list {
		lyr__w.Raw("<li")
		lyr__w.Attr("data-published", p.Published)
		lyr__w.Raw(">")
		lyr__w.Expr(p.Title)
		lyr__w.Raw(" (")
		lyr__w.Expr(p.Views)
		lyr__w.Raw(")</li>")
	}
	lyr__w.Raw("</ul>\n")
	if props.Depth < 2 {
`, file, name)
	for _, k := range kids {
		fmt.Fprintf(&b, `		if lyr__err := %[1]s.Render(ctx, lyr__w, %[1]s.Props{Title: props.Title + "/%[2]s", Post: first, Count: n, Featured: props.Count > 1, Depth: props.Depth + 1, Author: first.Author}, lyr.Slots{
			Default: func(lyr__w *lyr.Writer) error {
				lyr__w.Raw("<em>")
				lyr__w.Expr(first.Title)
				lyr__w.Raw("</em>")
				return lyr__w.Err()
			},
		}); lyr__err != nil {
			return lyr__err
		}
`, alias(k), k)
	}
	if self {
		b.WriteString(`		if lyr__err := Render(ctx, lyr__w, Props{Title: props.Title, Depth: props.Depth + 1}, lyr.Slots{}); lyr__err != nil {
			return lyr__err
		}
`)
	}
	b.WriteString(`	}
	lyr__w.Raw("</section>\n")
	return lyr__w.Err()
}
`)
	return b.String()
}

func alias(name string) string { return strings.ToUpper(name[:1]) + name[1:] }

const postsSrc = `package posts

import (
	"strconv"
	"time"
)

type Slug string

type Status int

const (
	Draft Status = iota
	Published
)

func (s Status) String() string {
	switch s {
	case Draft:
		return "draft"
	case Published:
		return "published"
	}
	return "status(" + strconv.Itoa(int(s)) + ")"
}

type Tag string

func (t Tag) String() string { return "#" + string(t) }

type Price float64

type Author struct {
	Name  string
	Email string
}

// Pointer receiver, nil-safe.
func (a *Author) String() string {
	if a == nil {
		return "anon"
	}
	return a.Name + " <" + a.Email + ">"
}

type Post struct {
	Title     string
	Slug      Slug
	Views     int
	Published bool
	Status    Status
	Author    *Author
	Tags      []string
	Score     float64
	Body      []byte
	Price     Price
	Created   time.Time
}

func (p Post) URL() string { return "/blog/" + string(p.Slug) + "/" }

var all = []Post{
	{Title: "Hello & welcome", Slug: "hello", Views: 42, Published: true, Status: Published, Author: &Author{"Ann", "ann@example.com"}, Tags: []string{"go", "web"}, Score: 4.5, Body: []byte("<p>body</p>"), Price: 1234567, Created: time.Date(2026, 10, 1, 12, 0, 0, 0, time.UTC)},
	{Title: "Second <post>", Slug: "second", Views: 7, Status: Draft, Score: 1e21, Price: 1000000},
	{Title: "Third", Slug: "third", Views: 0, Published: true, Status: 9},
}

func All() []Post { return all }
`

const renderMain = `// Code generated by lyr. DO NOT EDIT.

package main

import (
	"bytes"
	"fmt"
	"net/http"
	"os"

	lyr "github.com/bertrandkhe/lyr"
	"example.com/site/lyr_gen/app"
)

func main() {
	if len(os.Args) > 1 && os.Args[1] == "serve" { // links the net/http server, like a real dev server
		http.ListenAndServe(os.Args[2], http.HandlerFunc(func(rw http.ResponseWriter, r *http.Request) {
			var buf bytes.Buffer
			app.Pages[0].Render(&lyr.Ctx{Request: r}, lyr.NewWriter(&buf))
			rw.Write(buf.Bytes())
		}))
		return
	}
	for _, p := range app.Pages {
		var buf bytes.Buffer
		w := lyr.NewWriter(&buf)
		if err := p.Render(&lyr.Ctx{}, w); err != nil {
			fmt.Fprintln(os.Stderr, p.Name, err)
			os.Exit(1)
		}
		fmt.Printf("== %s %d bytes\n", p.Name, buf.Len())
		os.Stdout.Write(buf.Bytes())
	}
}
`
